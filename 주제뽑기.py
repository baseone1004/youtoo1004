def dup_status(title, my_titles, keywords=()):
    """내 영상 제목들과 비교. 제목 유사도 외에, 주제 핵심 낱말이 내 제목(해시태그 포함)에 몇 개 들어있는지도 본다."""
    keywords = [k for k in keywords if len(k) >= 2]
    best, best_t = 0.0, ""
    for mt in my_titles:
        s = similarity(title, mt)
        if keywords:
            found = sum(1 for k in keywords if k in mt)
            s = max(s, found / len(keywords) * 0.9)
        if s > best:
            best, best_t = s, mt
    if best >= 0.6:
        return "dup", best, best_t
    if best >= 0.35:
        return "similar", best, best_t
    return "new", best, best_t

def trend_keywords(bench):
    """벤치 채널 히트 영상 제목에서 여러 채널에 걸쳐 나오는 한국어 키워드."""
    per_channel = defaultdict(set)
    weight = Counter()
    for ch in bench:
        for v in ch.get("hits", []):
            for t in tokens(v["title"]):
                if HANGUL.fullmatch(t):
                    per_channel[t].add(ch["id"])
                    weight[t] += v.get("ratio", 1)
    ranked = sorted(per_channel, key=lambda t: (-len(per_channel[t]), -weight[t]))
    return [(t, len(per_channel[t])) for t in ranked[:40]]

def build_recommendations(mine, bench, used):
    my_titles = [v["title"] for v in (mine["videos"] if mine else [])] + used
    trends = trend_keywords(bench)
    trend_set = {t for t, _ in trends}
    all_hits = [(ch, v) for ch in bench for v in ch.get("hits", [])]

    cands = []
    for tp in TOPIC_BANK + generate_topics():
        tk = tokens(tp["t"])
        matched = sorted(tk & trend_set)
        evidence = []
        for ch, v in all_hits:
            ov = len(tk & tokens(v["title"]))
            if ov >= 2:
                evidence.append((ov, v.get("ratio", 0), ch["name"], v))
        evidence.sort(key=lambda x: (-x[0], -x[1]))
        score = tp["b"] + min(len(matched), 3) * 4 + min(len(evidence), 3) * 3 + random.randint(-3, 3)
        cands.append(dict(tp, score=min(score, 99), matched=matched, evidence=evidence[:2], src=tp.get("src", "bank")))

    seen = set()
    for ch, v in sorted(all_hits, key=lambda x: -x[1].get("ratio", 0))[:25]:
        ko = [t for t in tokens(v["title"]) if HANGUL.fullmatch(t)]
        kws = [t for t in ko if t in trend_set] or sorted(ko, key=len, reverse=True)[:1]
        if not kws or len(ko) < 2 or kws[0] in seen:
            continue
        k = kws[0]
        seen.add(k)
        cands.append(dict(
            c="벤치", t=random.choice(DERIVE_FRAMES).format(k=k),
            h=f"'{ch['name']}' 채널에서 평소의 {v.get('ratio')}배 터진 영상의 핵심 단어 '{k}'를 우리 채널 방식으로 다시 묻습니다.",
            th=f"{k}의 이유", w=f"제목은 다듬어서 쓰세요. 참고: {v['title']}",
            score=min(66 + min(v.get("ratio", 0), 8) * 2, 84), matched=[k],
            evidence=[(2, v.get("ratio", 0), ch["name"], v)], src="derived"))

    for c in cands:
        st, sim, near = dup_status(c["t"], my_titles, c.get("k", ()))
        c["status"], c["sim"], c["near"] = st, round(sim, 2), near
        if st == "similar":
            c["score"] -= 15

    fresh = sorted((c for c in cands if c["status"] != "dup"), key=lambda c: -c["score"])
    dups = [c for c in cands if c["status"] == "dup"]

    # 7일 × 2편: 카테고리당 최대 3편, 같은 날 두 편은 다른 카테고리, 벤치 파생은 제외 (제목 손질이 필요하므로)
    need = 하루_편수 * 일정_일수
    pool, per_cat = [], Counter()
    def looks_like(c, chosen):
        return any(similarity(c["t"], x["t"]) >= 0.5 or set(c.get("k", [])) == set(x.get("k", [])) for x in chosen)
    for c in fresh:
        if c["src"] == "derived" or per_cat[c["c"]] >= 3 or looks_like(c, pool):
            continue
        pool.append(c); per_cat[c["c"]] += 1
        if len(pool) == need:
            break
    top = []
    while pool:
        a = pool.pop(0)
        top.append(a)
        if len(top) % 하루_편수 == 1 and pool:
            j = next((i for i, x in enumerate(pool) if x["c"] != a["c"]), 0)
            top.append(pool.pop(j))
    rest = []
    for c in fresh:
        if c not in top and not looks_like(c, top + rest):
            rest.append(c)
        if len(rest) == 후보_수:
            break
    return top, rest, dups, trends

