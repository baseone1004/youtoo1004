YDL_OPTS = {"quiet": True, "no_warnings": True, "extract_flat": True, "skip_download": True, "ignoreerrors": True,
            "extractor_args": {"youtube": {"lang": ["ko"]}}}

def ydl_extract(url, playlistend=None):
    opts = dict(YDL_OPTS)
    if playlistend:
        opts["playlistend"] = playlistend
    with yt_dlp.YoutubeDL(opts) as y:
        try:
            return y.extract_info(url, download=False)
        except Exception as e:
            print(f"   ! 가져오기 실패: {url} ({e})")
            return None

def norm_channel_url(url):
    url = url.strip()
    if not url:
        return ""
    if not url.startswith("http"):
        url = "https://www.youtube.com/" + url.lstrip("/")
    url = re.sub(r"/(videos|shorts|streams|featured|about)/?$", "", url)
    return url

def fetch_channel(url, limit):
    """채널의 최근 영상 목록을 가져온다. 유튜브 API 키가 있으면 공식 API(조회수 정확), 없으면 yt-dlp."""
