def is_korean(text):
    """제목 글자의 40% 이상이 한글이면 한국어 영상으로 본다."""
    letters = re.findall(r"[가-힣A-Za-z]", text or "")
    return bool(letters) and sum(1 for ch in letters if "가" <= ch <= "힣") / len(letters) >= 0.4

def tokens(text):
    text = re.sub(r"#(\S+)", r"  ", text)
    text = re.sub(r"\[.*?\]|\(.*?\)|【.*?】", " ", text)
    text = re.sub(r"[^\w가-힣\s]", " ", text)
    out = set()
    for w in text.split():
        w = w.strip()
        if not w or w.isdigit():
            continue
        w = VERB_END.sub("", w)
        for p in PARTICLES:
            if w.endswith(p) and len(w) - len(p) >= 2:
                w = w[: -len(p)]
                break
        w = VERB_END.sub("", w)
        if len(w) >= 2 and w.lower() not in STOP:
            out.add(w)
    return out

def bigrams(text):
    s = re.sub(r"[^가-힣a-zA-Z0-9]", "", text)
    return {s[i:i + 2] for i in range(len(s) - 1)}

def similarity(a, b):
    """두 제목의 유사도 0~1. 토큰 겹침 비율과 글자 바이그램 자카드 중 큰 값."""
    ta, tb = tokens(a), tokens(b)
    tok = 0.0
    if len(ta) >= 2 and len(tb) >= 2:
        tok = len(ta & tb) / min(len(ta), len(tb))
    ba, bb = bigrams(a), bigrams(b)
    bi = len(ba & bb) / len(ba | bb) if ba and bb else 0.0
    return max(tok, bi * 1.25)

