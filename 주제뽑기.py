def save_plan(top):
    """대본생성.py 가 읽는 계획.json — 같은 제목의 대본 파일이 이미 있으면 그 정보는 남긴다."""
    old = {}
    if os.path.exists("계획.json"):
        try:
            with open("계획.json", encoding="utf-8") as f:
                old = {t["제목"]: t.get("대본파일") for t in json.load(f)}
        except Exception:
            old = {}
    today = datetime.date.today()
    plan = []
    for i, c in enumerate(top):
        u = make_upload(c)
        d = today + datetime.timedelta(days=i // 하루_편수)
        plan.append({"날짜": d.isoformat(), "순번": i % 하루_편수 + 1, "제목": c["t"], "유튜브제목": u["title"],
                     "카테고리": c["c"], "오프닝": c["h"], "썸네일": c["th"], "다룰내용": c.get("p", []),
                     "출처후보": c.get("s", []), "태그": c.get("k", []), "대본파일": old.get(c["t"]) or ""})
        c["대본파일"] = plan[-1]["대본파일"]
    with open("계획.json", "w", encoding="utf-8") as f:
        json.dump(plan, f, ensure_ascii=False, indent=1)

def save_candidates(rest):
    """대본선택.py 가 '다음 후보'도 고를 수 있게 같은 형식으로 저장."""
    out = [{"제목": c["t"], "카테고리": c["c"], "오프닝": c["h"], "썸네일": c["th"], "다룰내용": c.get("p", []),
            "출처후보": c.get("s", []), "태그": c.get("k", [])} for c in rest]
    with open("후보.json", "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)

def main():
    cfg = load_config()
    warnings = []
    random.seed(datetime.date.today().isocalendar()[1])   # 같은 주엔 같은 결과

    print("① 내 채널 확인 중...")
    mine = None
    if cfg["내_채널"].strip():
        mine = fetch_channel(cfg["내_채널"], 200)
        if mine:
            print(f"   {mine['name']} · {len(mine['videos'])}편")
        else:
            warnings.append("내 채널 주소를 읽지 못했습니다. 설정.json 의 내_채널 을 확인하세요.")
    else:
        print("   (설정.json 에 내_채널 이 비어 있음)")
    used = load_used_topics()

    print("② 비슷한 채널 찾는 중...")
    exclude_ids = {mine["id"]} if mine and mine.get("id") else set()
    urls = [norm_channel_url(u) for u in cfg["벤치_채널_추가"] if u.strip()]
    for cid, name, url, hits in discover_channels(검색어, exclude_ids, 제외_채널_단어, 벤치_채널_수):
        print(f"   {name}")
        if url not in urls:
            urls.append(url)

    print(f"③ 채널 {len(urls)}곳에서 터진 영상 찾는 중...")
    bench = []
    for u in urls:
        ch = fetch_channel(u, 채널당_영상_수)
        if not ch or not ch["videos"]:
            warnings.append(f"채널을 읽지 못했습니다: {u}")
            continue
        if mine and ch.get("id") == mine.get("id"):
            continue
        bench.append(analyze_channel(ch))

    print("④ 7일치 14편 고르는 중...")
    top, rest, dups, trends = build_recommendations(mine, bench, used)
    if len(top) < 하루_편수 * 일정_일수:
        warnings.append(f"새 주제가 {len(top)}편밖에 안 남았습니다. 현상_추가.txt 에 줄을 추가하면 다시 늘어납니다.")
    save_plan(top)
    save_candidates(rest)
    with open("트렌드.json", "w", encoding="utf-8") as f:
        json.dump({"날짜": datetime.date.today().isoformat(), "단어": [t for t, _ in trends[:30]]}, f, ensure_ascii=False, indent=1)
    # 비슷한 채널에서 '평소보다 몇 배' 터진 영상 — 새 주제 추천·제목·썸네일 문구의 참고 자료
    hits = []
    for ch in bench:
        for v in ch.get("hits", []):
            hits.append(dict(title=v["title"], channel=ch["name"], views=v["views"], ratio=v.get("ratio", 0), url=v["url"],
                             thumb=f"https://i.ytimg.com/vi/{v['id']}/hqdefault.jpg" if v.get("id") else ""))
    hits.sort(key=lambda v: -v["ratio"])
    with open("벤치_히트.json", "w", encoding="utf-8") as f:
        json.dump({"날짜": datetime.date.today().isoformat(), "채널": [dict(name=c["name"], url=c["url"], subs=c.get("subs", 0)) for c in bench],
                   "히트": hits[:60]}, f, ensure_ascii=False, indent=1)
    out = os.path.join(BASE, "주제_리포트.html")
    with open(out, "w", encoding="utf-8") as f:
        f.write(render(mine, bench, top, rest, dups, trends, warnings))
    print(f"\n완료! 이번 주 {len(top)}편 · 후보 {len(rest)}편 · 겹쳐서 뺀 주제 {len(dups)}개")
    if "--no-browser" not in sys.argv:
        webbrowser.open("file:///" + out.replace("\\", "/"))

if __name__ == "__main__":
    main()
